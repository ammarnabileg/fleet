"""Keeps the driver app's strings and the server's translation seed in step (run from the repository root after
changing an arb file or a seed file, then `flutter gen-l10n`, then run it again for the wrapper):

1. backend/app/modules/i18n/seed/{ar,en}.json <- the app's arb files (Arabic and English are written in the app) and
   the live-status cards' built-in texts;
2. driver_app/lib/l10n/app_<lang>.arb of every other seed language <- its seed (the app's built-in copy, for the first
   run and offline);
3. driver_app/lib/l10n/remote_localizations.dart <- the generated AppLocalizations: each string is looked up in the
   dashboard's copy first (see lib/core/translations.dart).

    python3 driver_app/tool/l10n_sync.py
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
L10N = ROOT / "driver_app/lib/l10n"
SEED = ROOT / "backend/app/modules/i18n/seed"
OWN = ("ar", "en")


def load(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def dump(path: Path, data: dict) -> None:
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def strings(arb: dict) -> dict:
    return {k: v for k, v in arb.items() if not k.startswith("@")}


def status_templates() -> dict[str, dict[str, str]]:
    sys.path.insert(0, str(ROOT / "backend"))
    from app.modules.driver_status.templates import DEFAULTS

    out: dict[str, dict[str, str]] = {lang: {} for lang in OWN}
    for code, t in DEFAULTS.items():
        for field in ("name", "title", "subtitle"):
            for lang in OWN:
                out[lang][f"{code}.{field}"] = t[field][lang]
    return out


def seeds() -> None:
    cards = status_templates()
    for lang in OWN:
        path = SEED / f"{lang}.json"
        data = load(path) if path.exists() else {}
        data["app"] = strings(load(L10N / f"app_{lang}.arb"))
        data["status_templates"] = cards[lang]
        dump(path, data)


def arbs() -> None:
    order = list(strings(load(L10N / "app_en.arb")))
    for path in sorted(SEED.glob("*.json")):
        lang = path.stem
        if lang in OWN:
            continue
        app = load(path).get("app", {})
        arb = {"@@locale": lang} | {k: app[k] for k in order if k in app}
        dump(L10N / f"app_{lang}.arb", arb)


GETTER = re.compile(r"^  String get (\w+);$", re.M)
METHOD = re.compile(r"^  String (\w+)\(([^)]*)\);$", re.M)


def wrapper() -> None:
    src = (L10N / "app_localizations.dart").read_text(encoding="utf-8")
    body = src[src.index("abstract class AppLocalizations") :]
    out = [
        "// Generated by tool/l10n_sync.py from app_localizations.dart: do not edit.",
        "// ignore_for_file: type=lint",
        "",
        "import 'app_localizations.dart';",
        "import '../core/translations.dart';",
        "",
        "/// The app's strings: the dashboard's text when there is a valid one, else the built-in one.",
        "class RemoteLocalizations extends AppLocalizations {",
        "  RemoteLocalizations(this._base, this._remote) : super(_base.localeName);",
        "",
        "  final AppLocalizations _base;",
        "  final RemoteStrings _remote;",
        "",
    ]
    members = sorted(
        [(m.start(), m.group(1), None) for m in GETTER.finditer(body)]
        + [(m.start(), m.group(1), m.group(2)) for m in METHOD.finditer(body)]
    )
    for _, name, params in members:
        out.append("  @override")
        if params is None:
            out.append(f"  String get {name} => _remote.text('{name}') ?? _base.{name};")
            continue
        names = [p.strip().split()[-1] for p in params.split(",") if p.strip()]
        args = ", ".join(f"'{n}': {n}" for n in names)
        call = ", ".join(names)
        out.append(f"  String {name}({params}) => _remote.format('{name}', {{{args}}}) ?? _base.{name}({call});")
    out.append("}")
    (L10N / "remote_localizations.dart").write_text("\n".join(out) + "\n", encoding="utf-8")


if __name__ == "__main__":
    seeds()
    arbs()
    wrapper()
